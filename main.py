def tobinary(num_10):
    num_10 = abs(num_10) # работаем с модулем, чтобы обрабатывать и отрицательные числа
    if num_10 == 0:
        return "0"
    num_2 = ""
    while num_10 != 0:
        ost = str(num_10 % 2) # остаток от деления(0 или 1)
        num_2 = ost + num_2 # приписываем слева
        num_10 //= 2 # целочисленно делим число
    return num_2

